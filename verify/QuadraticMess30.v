Lemma criticalN (a b c d f:N):
  (1<=a)%N -> b=(2*a+2)%N -> N.even d=true ->
  (2<=d)%N -> (d+4<=2*c)%N -> (1<=f)%N ->
  halts tm (Mark (N.to_nat a) ([1]^^N.to_nat b *> [0;1]^^N.to_nat c *>
    [1]^^N.to_nat d *> [0;1]^^N.to_nat f *> 0inf)%sym).
Proof.
  intros. applys_eq (Critical_spec (N.to_nat a) (N.to_nat b) (N.to_nat c)
    (N.to_nat d) (N.to_nat f)); try apply even_nat; auto; flia.
Qed.
Lemma smallN (a b c d f:N):
  N.odd b=true -> (b+1<=2*a)%N -> N.even c=true -> (2<=c)%N ->
  N.even d=true -> (2<=d)%N -> (d+b<=2*a+3)%N -> N.odd f=true ->
  halts tm (Mark (N.to_nat a) ([1]^^N.to_nat b *> [0;1]^^N.to_nat c *>
    [1]^^N.to_nat d *> [0;1]^^N.to_nat f *> 0inf)%sym) <->
  halts tm (Pure (N.to_nat (2*a+c+f+5))).
Proof.
  intros. nsimp. applys_eq (OddSmall_spec (N.to_nat a) (N.to_nat b) (N.to_nat c)
    (N.to_nat d) (N.to_nat f)); try (apply even_nat || apply odd_nat); auto; flia.
Qed.
Lemma middleN (a b c d f:N):
  N.even b=true -> N.even d=true -> (2<=b)%N -> (b+4<=2*a)%N ->
  (1<=c)%N -> (1<=f)%N -> (2*c+2<=d)%N -> (b+d+4<=2*a+2*c)%N ->
  halts tm (Mark (N.to_nat a) ([1]^^N.to_nat b *> [0;1]^^N.to_nat c *>
    [1]^^N.to_nat d *> [0;1]^^N.to_nat f *> 0inf)%sym) <->
  halts tm (Mark 3 ([1]^^N.to_nat (2*a+2*c-b-d-4) *>
    [0;1]^^N.to_nat (b+d+2) *> [1]^^N.to_nat (2*f-2) *> [0;1] *> 0inf)%sym).
Proof.
  intros. nsimp. applys_eq (EvenMiddle_spec (N.to_nat a) (N.to_nat b) (N.to_nat c)
    (N.to_nat d) (N.to_nat f)); try apply even_nat; auto; flia.
Qed.

