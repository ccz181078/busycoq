Hypothesis marked_sound: forall xs, Post (marked_step xs) -> MP xs.

Lemma step_sound xs: Post (step xs) -> P xs.
Proof.
  destruct xs as [|[w a] xs]; [discriminate|]. destruct w; [discriminate|].
  destruct xs as [|[w b] xs].
  - cbn [step]. destruct (N.leb 2 a && N.even a) eqn:E; [|discriminate].
    intro H. apply marked_post in H. guards. words.
    destruct (HalfEven (N.to_nat a) ltac:(lia) (even_nat _ E)) as [k Ek].
    change (halts tm (Mark 3 ([1]^^N.to_nat (2*a-2) *> [0;1] *> 0inf)%sym)) in H.
    change (halts tm (Pure (N.to_nat a))). nsimp. rewrite Ek in *.
    eapply halts_evstep; [exact H|]. follow (Entry k).
    applys_eq (Entry2 k); flia.
  - destruct w; [|discriminate]. cbn [step].
    destruct (N.eqb a 2 && N.eqb b 1) eqn:E.
    + guards. subst a b. intro H. apply marked_sound in H. exact H.
    + destruct (N.odd a && N.leb 2 b) eqn:E0; [|discriminate].
      intro H. apply marked_post in H. guards. words.
      destruct (HalfOdd (N.to_nat a) (odd_nat a ltac:(assumption))) as [k Ek].
      change (halts tm (Mark (N.to_nat a)
        ([1]^^N.to_nat (b-2) *> denote xs *> 0inf)%sym)) in H.
      change (halts tm (Phi ([0;1]^^N.to_nat a *> [1]^^N.to_nat b *>
        denote xs *> 0inf)%sym)). nsimp. rewrite Ek in *.
      eapply halts_evstep; [exact H|].
      replace (N.to_nat b) with (2+(N.to_nat b-2))%nat at 1 by lia.
      apply Prefix.
Qed.

