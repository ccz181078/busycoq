Definition word := (bool * N)%type.
Definition words := list word.
Definition cons_word (w:bool) (n:N) (xs:words) : words :=
  if N.eqb n 0 then xs else
  match xs with
  | (v,m)::ys => if Bool.eqb w v then (w,n+m)::ys else (w,n)::xs
  | [] => [(w,n)]
  end.
Fixpoint normalize (xs:words) : words :=
  match xs with [] => [] | (w,n)::xs => cons_word w n (normalize xs) end.
Definition marked xs := normalize ((false,2)::(true,1)::xs).
Definition result := (words + bool)%type.
Definition next xs : result := inl (normalize xs).
Definition next_marked xs : result := inl (marked xs).

Fixpoint split_even (xs:words) : option words :=
  match xs with
  | [(false,f)] => if N.leb 1 f then Some [(true,2*f-2);(false,1)] else None
  | (false,a)::(true,b)::xs =>
    if N.even b && N.leb 2 b && N.leb (b+4) (2*a) then
      match split_even xs with
      | Some ys => Some ((true,2*a-b-4)::(false,b+2)::ys)
      | None => None
      end
    else None
  | _ => None
  end.
Definition split_fallback xs : result :=
  match split_even xs with
  | Some ys => next_marked ((false,3)::ys)
  | None => inr false
  end.
Definition merge_fallback a b c d tail xs : result :=
  if N.leb 2 a && N.even b && N.leb 2 b && N.leb 1 c && N.leb (b+2) (2*a) &&
     N.leb (2*a+2*c+3) (d+b) then
    next ((false,2*a+2*c+5)::(true,d+b-2*a-2*c-3)::tail)
  else if N.odd b && N.leb (b+1) (2*a) && N.even c && N.leb 2 c &&
          N.leb (2*a+3) (d+b) then
    next ((false,2*a+c+5)::(true,d+b-2*a-3)::tail)
  else split_fallback xs.

Definition marked_step (xs:words) : result :=
  match xs with
  | [(false,n)] =>
    if N.leb 2 n && N.even n then
      next_marked [(false,3);(true,2*n-2);(false,1)] else inr false
  | (false,a)::(true,b)::(false,c)::tail =>
    if N.leb 1 a && N.leb (2*a+5) b then
      next_marked ((false,2*a+5)::(true,b-2*a-5)::(false,c)::tail)
    else match tail with
    | [] =>
      if N.eqb a 27 && N.eqb b 52 && N.eqb c 1 then
        next_marked [(false,58)]
      else if N.leb 1 a && N.odd b && N.leb b (2*a+3) && N.odd c then
        next [(false,2*a+c+5)]
      else split_fallback xs
    | (true,d)::tail' =>
      match tail' with
      | [(false,f)] =>
        if N.leb 1 a && N.eqb b (2*a+2) && N.even d &&
           N.leb 2 d && N.leb (d+4) (2*c) && N.leb 1 f then inr true
        else if N.odd b && N.leb (b+1) (2*a) && N.even c && N.leb 2 c &&
                N.even d && N.leb 2 d && N.leb (d+b) (2*a+3) && N.odd f then
          next [(false,2*a+c+f+5)]
        else if N.even b && N.even d && N.leb 2 b && N.leb 1 c && N.leb 1 f && N.leb (b+4) (2*a) &&
                N.leb (2*c+2) d && N.leb (b+d+4) (2*a+2*c) then
          next_marked [(false,3);(true,2*a+2*c-b-d-4);
                       (false,b+d+2);(true,2*f-2);(false,1)]
        else merge_fallback a b c d tail' xs
      | _ => merge_fallback a b c d tail' xs
      end
    | _ => inr false
    end
  | _ => inr false
  end.

Definition step (xs:words) : result :=
  match xs with
  | [(false,n)] =>
    if N.leb 2 n && N.even n then
      next_marked [(false,3);(true,2*n-2);(false,1)] else inr false
  | (false,a)::(true,b)::tail =>
    if N.eqb a 2 && N.eqb b 1 then marked_step tail
    else if N.odd a && N.leb 2 b then next_marked ((false,a)::(true,b-2)::tail)
    else inr false
  | _ => inr false
  end.
Definition check fuel : bool :=
  match Eqb.N_iter_until step (inl [(false,28)]) fuel with
  | inr true => true | _ => false
  end.

