Lemma marked_step_sound xs: Post (marked_step xs) -> MP xs.
Proof.
  destruct xs as [|[w a] xs]; [discriminate|]. destruct w; [discriminate|].
  destruct xs as [|[w b] xs].
  - cbn [marked_step]. destruct (N.leb 2 a && N.even a) eqn:E; [|discriminate].
    guards. apply pure_marked_sound; assumption.
  - destruct w; [|discriminate]. destruct xs as [|[w c] tail]; [discriminate|].
    destruct w; [discriminate|]. cbn [marked_step].
    destruct (N.leb 1 a && N.leb (2*a+5) b)%N eqn:E.
    + guards. apply high_marked_sound; assumption.
    + destruct tail as [|[w d] tail].
      * apply end_block_sound.
      * destruct w; [|discriminate]. destruct tail as [|[w f] tail].
        -- apply merge_fallback_sound.
        -- destruct w; [apply merge_fallback_sound|].
           destruct tail as [|h tail]; [|apply merge_fallback_sound].
           destruct (N.leb 1 a && N.eqb b (2*a+2) && N.even d &&
             N.leb 2 d && N.leb (d+4) (2*c) && N.leb 1 f)%N eqn:C.
           ++ intros _. guards. words. repeat rewrite app_nil_r.
              change (halts tm (Mark (N.to_nat a) ([1]^^N.to_nat b *> [0;1]^^N.to_nat c *>
                [1]^^N.to_nat d *> [0;1]^^N.to_nat f *> 0inf)%sym)).
              apply criticalN; assumption.
           ++ destruct (N.odd b && N.leb (b+1) (2*a) && N.even c && N.leb 2 c &&
                N.even d && N.leb 2 d && N.leb (d+b) (2*a+3) && N.odd f)%N eqn:S.
              ** rewrite next_post. intro Hr. guards. words. repeat rewrite app_nil_r in *.
                 change (halts tm (Mark (N.to_nat a) ([1]^^N.to_nat b *> [0;1]^^N.to_nat c *>
                   [1]^^N.to_nat d *> [0;1]^^N.to_nat f *> 0inf)%sym)).
                 rewrite smallN; auto.
              ** destruct (N.even b && N.even d && N.leb 2 b && N.leb 1 c && N.leb 1 f &&
                   N.leb (b+4) (2*a) && N.leb (2*c+2) d && N.leb (b+d+4) (2*a+2*c))%N eqn:M.
                 --- rewrite marked_post. intro Hr. guards. words. repeat rewrite app_nil_r in *.
                     change (halts tm (Mark (N.to_nat a) ([1]^^N.to_nat b *> [0;1]^^N.to_nat c *>
                       [1]^^N.to_nat d *> [0;1]^^N.to_nat f *> 0inf)%sym)).
                     rewrite middleN; auto.
                 --- apply merge_fallback_sound.
Qed.

